const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('dist/index.html', 'utf8');
const tag = 'https://www.googletagmanager.com/gtag/js?id=G-7SVFRB09B6';
assert.equal(html.split(tag).length, 2);
assert(html.indexOf('analytics-host.js?v=1.14') < html.indexOf(tag));
assert(!/analytics-choice|ready-analytics/.test(html));
assert(html.includes("script-src 'self' https://www.googletagmanager.com"));
assert(html.includes('https://*.google-analytics.com'));
const window = {};
vm.runInNewContext(fs.readFileSync('dist/analytics-host.js', 'utf8'), {window});
const [consent, init, config] = Array.from(window.dataLayer, entry => Array.from(entry));
assert.equal(consent[2].analytics_storage, 'granted');
for (const key of ['ad_storage', 'ad_user_data', 'ad_personalization']) assert.equal(consent[2][key], 'denied');
assert.equal(init[0], 'js');
assert.equal(config[1], 'G-7SVFRB09B6');
assert.equal(config[2].page_location, 'https://readytogether.info/');
assert.equal(window.dataLayer.length, 3);
console.log('PASS single main-page GA4 tag with automatic page views');
